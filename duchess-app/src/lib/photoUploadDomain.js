export class InvalidPhotoUploadTransitionError extends Error {
  constructor(status, event) {
    super(`Invalid photo upload transition: ${String(status)} + ${String(event)}`)
    this.name = 'InvalidPhotoUploadTransitionError'
    this.status = status
    this.event = event
  }
}

const S = PHOTO_UPLOAD_STATUSES
const E = PHOTO_UPLOAD_EVENTS


export function isPhotoUploadStatus(value) {
  return Object.values(PHOTO_UPLOAD_STATUSES).includes(value)
}

function isPhotoUploadEvent(value) {
  return Object.values(PHOTO_UPLOAD_EVENTS).includes(value)
}

export function isUploadTransportPermitted(status) {
  return status === PHOTO_UPLOAD_STATUSES.UPLOADING
}

export function transitionPhotoUpload(status, event) {
  if (!isPhotoUploadStatus(status) || !isPhotoUploadEvent(event)) {
    throw new InvalidPhotoUploadTransitionError(status, event)
  }

  const decision = TRANSITIONS[`${status}::${event}`]
  if (!decision) {
    throw new InvalidPhotoUploadTransitionError(status, event)
  }

  return decision
}

  [`${S.DRAFT_QUEUED}::${E.REPORT_ID_PROVEN}`]: STATE(S.QUEUED),
  [`${S.DRAFT_QUEUED}::${E.REPORT_RESULT_AMBIGUOUS}`]: STATE(S.REPORT_LINK_UNKNOWN),
  [`${S.DRAFT_QUEUED}::${E.DISCARD_REQUESTED}`]: DELETE_LOCAL,

  [`${S.REPORT_LINK_UNKNOWN}::${E.REPORT_ID_PROVEN}`]: STATE(S.QUEUED),
  [`${S.REPORT_LINK_UNKNOWN}::${E.DISCARD_REQUESTED}`]: DELETE_LOCAL,

